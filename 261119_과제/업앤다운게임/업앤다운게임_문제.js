// ════════════════════════════════
// ── Q1단계: 게임 반복 여부 변수 ──
// ════════════════════════════════

// Q1. 처음에는 무조건 게임이 시작되어야 합니다. 알맞은 불리언 값은?
let playAgain = true;

// ════════════════════════════════
// ── Q2단계: 바깥 while — 게임 전체 반복 ──
// ════════════════════════════════

// Q2. playAgain이 true인 동안 게임을 반복하도록 조건을 채우세요.
while (playAgain) {
  // 정답: 1 ~ 100 사이의 랜덤 정수 (미리 완성된 코드 — 그대로 사용하세요)
  const answer = Math.floor(Math.random() * 100) + 1;

  // Q3. 입력한 숫자는 게임 중 계속 바뀝니다. 알맞은 키워드는?
  let guess = 0;
  // 게임 횟수
  let life = 3;

  // 💡 테스트할 때 정답을 미리 보고 싶다면 아래 주석을 해제
  // console.log("정답:", answer);

  alert("🎮 업앤다운 게임을 시작합니다!\n1부터 100 사이의 숫자를 맞혀보세요.");

  // ════════════════════════════════
  // ── Q3단계: 안쪽 while — 정답을 맞힐 때까지 반복 ──
  // ════════════════════════════════

  // Q4. "아직 못 맞혔으면" 계속 반복하도록 연산자를 채우세요.
  // 선택지: ===  !==  >  <
  while (guess !== answer) {
    // 게임횟수가 소진
    if (life === 0) {
      alert(`당신의 목숨은 ${life}입니다.`);
      break;
    }
    // Q5. 사용자에게 입력을 받는 함수는?
    const input = prompt("1 ~ 100 사이 숫자를 입력하세요.");

    // 취소 버튼을 누르면 input에는 null이 들어옵니다 → 이번 판 포기
    if (input === null) {
      alert(`이번 판은 포기! 정답은 ${answer}였습니다.`);
      break;
    }

    // Q6. prompt로 받은 값은 '문자열'입니다. 숫자로 바꾸세요.
    guess = Number(input);

    // Q7. 숫자가 아니거나 "또는" 범위를 벗어나면 다시 입력받게 하세요.
    if (isNaN(guess) || guess < 1 || guess > 100) {
      alert("⚠️ 1 ~ 100 사이의 숫자만 입력하세요!");
      continue;
    }

    // ── Q4단계: UP / DOWN / 정답 판정 ──

    // Q8. 정답보다 크면 DOWN, 작으면 UP, 둘 다 아니면 정답!
    if (guess > answer) {
      alert(`${guess}보다 작아요! DOWN ⬇️`);
      life--;
    } else if (guess < answer) {
      alert(`${guess}보다 커요! UP ⬆️`);
      life--;
    } else {
      alert(`🎉 정답! ${answer}을(를) 맞혔어요!`);
    }
  }

  // ════════════════════════════════
  // ── Q5단계: 다시 할지 묻기 ──
  // ════════════════════════════════

  // Q9. [확인]이면 true, [취소]면 false를 돌려주는 함수는?
  playAgain = confirm("게임을 다시 하시겠습니까?");
}

alert("게임을 종료합니다. 플레이해줘서 고마워요! 👋");
