// 3. 15개를 모두 채우면 오류 없이 실행돼요. 구역 ①②③ 맨 위 주석의 '성공' 모습과 결과를 비교해요.
// ⚠ while 안에서 값을 바꾸지 않으면 끝나지 않는 '무한 반복'이 돼요.
//   실행이 멈추지 않으면 터미널에서 Ctrl + C 를 눌러 멈추고 빈칸을 다시 확인하세요.
